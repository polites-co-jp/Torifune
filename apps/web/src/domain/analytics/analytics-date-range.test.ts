import { describe, expect, it } from 'vitest';
import { isValidRange } from './analytics';

/**
 * アナリティクスの日付の範囲（046-input-500-nul-and-ranges 設計 §6.4、受け入れ条件 #37）。
 *
 * 規則は「`YYYY-MM-DD` の形で、暦にあり、年が `0001` 以上」（`0001-01-01`〜`9999-12-31`）。
 * PostgreSQL の `date` は西暦 0 年を持たない（紀元前 1 年の次が西暦 1 年）ので、
 * 年 `0000` を通すと `22008` で 500 になっていた（B2）。上限は形（4 桁）で `9999-12-31` に決まる。
 */

describe('#37 isValidRange は西暦 0 年を含む期間を偽にする', () => {
  it.each([
    ['0000-01-01', '0000-01-02'],
    ['0000-12-31', '0001-01-01'],
    ['0000-02-29', '0000-02-29'],
    ['0000-01-01', '2026-09-25'],
  ])('#37 (%s, %s) → 偽', (from, to) => {
    expect(isValidRange(from, to)).toBe(false);
  });
});

describe('#37 isValidRange は西暦 1〜9999 年の実在する日付を真にする', () => {
  it.each([
    ['0001-01-01', '0001-01-01'],
    ['0001-01-01', '0001-01-02'],
    ['0099-12-31', '0100-01-01'],
    ['9999-12-31', '9999-12-31'],
    ['2024-02-29', '2024-02-29'],
  ])('#37 (%s, %s) → 真', (from, to) => {
    expect(isValidRange(from, to)).toBe(true);
  });
});

describe('#37 変わらないもの', () => {
  it('#37 暦に無い日付（2026-02-30）は従来どおり偽', () => {
    expect(isValidRange('2026-02-30', '2026-03-01')).toBe(false);
  });

  it('#37 開始日が終了日より後なら従来どおり偽', () => {
    expect(isValidRange('0001-01-02', '0001-01-01')).toBe(false);
  });
});
